func glyphBitmap(r rune) [glyphH]string {
	if g, ok := cellFont[r]; ok {
		return g
	}
	return [glyphH]string{".....", "#####", "#####", "#####", "#####", "#####", "....."}
}

// Image rasterises the screen. scale is pixels per bitmap pixel; at scale 2 a
// cell is 11 by 18 pixels.
func (s *Screen) Image(scale int) *image.RGBA {
	if scale < 1 {
		scale = 1
	}
	cw := glyphW*scale + cellPadX*scale
	ch := (glyphH + cellRiseY + cellDropY) * scale
	img := image.NewRGBA(image.Rect(0, 0, s.Cols*cw, s.Rows*ch))

	fill := func(px, py int, c RGB) {
		for y := 0; y < scale; y++ {
			o := img.PixOffset(px, py+y)
			for x := 0; x < scale; x++ {
				i := o + x*4
				img.Pix[i], img.Pix[i+1], img.Pix[i+2], img.Pix[i+3] = c[0], c[1], c[2], 0xff
			}
		}
	}

	for y := 0; y < s.Rows; y++ {
		for x := 0; x < s.Cols; x++ {
			cell := s.Cells[y*s.Cols+x]
			bitmap := glyphBitmap(cell.Ch)
			for gy := 0; gy < glyphH+cellRiseY+cellDropY; gy++ {
				for gx := 0; gx < glyphW+cellPadX; gx++ {
					c := cell.Bg
					inGlyph := gy >= cellRiseY && gy < cellRiseY+glyphH && gx < glyphW
					if inGlyph && bitmap[gy-cellRiseY][gx] == '#' {
						c = cell.Fg
					}
					fill(x*cw+gx*scale, y*ch+gy*scale, c)
				}
			}
		}
	}
	return img
}
